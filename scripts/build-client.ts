// Bundles the browser client into src/client/bundle.generated.ts so the server
// (and the compiled binary) can serve it at /_onebase/client.js.

const result = await Bun.build({
  entrypoints: [new URL("../src/client/index.ts", import.meta.url).pathname],
  target: "browser",
  format: "esm",
  minify: true,
});
if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}
const code = await result.outputs[0]!.text();
await Bun.write(
  new URL("../src/client/bundle.generated.ts", import.meta.url).pathname,
  `// Generated by scripts/build-client.ts. Do not edit.\nexport const clientBundle = ${JSON.stringify(code)};\n`,
);
console.log(`client bundle: ${(code.length / 1024).toFixed(1)} KB`);
