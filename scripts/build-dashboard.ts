// Bundles the dashboard (src/dashboard) into src/dashboard/bundle.generated.ts, so the
// server and the compiled binary can serve it at /_admin without any files on disk.

const root = new URL("../src/dashboard/", import.meta.url).pathname;
const result = await Bun.build({
  entrypoints: [`${root}app.tsx`],
  target: "browser",
  format: "esm",
  minify: true,
  define: { "process.env.NODE_ENV": '"production"' },
});
if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}
const js = await result.outputs.find((o) => o.kind === "entry-point")!.text();
const css = (await Bun.file(`${root}style.css`).text()).replace(/\n\s*/g, "\n");
await Bun.write(
  `${root}bundle.generated.ts`,
  `// Generated by scripts/build-dashboard.ts. Do not edit.\nexport const dashboardAssets = { js: ${JSON.stringify(js)}, css: ${JSON.stringify(css)} };\n`,
);
console.log(`dashboard bundle: ${(js.length / 1024).toFixed(1)} KB js, ${(css.length / 1024).toFixed(1)} KB css`);
